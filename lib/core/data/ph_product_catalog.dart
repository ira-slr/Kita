  /// Returns all unique categories from the product list.
  static List<String> get categories {
    final cats = products.map((p) => p.category).toSet().toList();
    cats.sort();
    return cats;
  }

  /// Filters products by [query] (name or variant) and optionally by [category].
  static List<PhProduct> search(String query, {String? category}) {
    final q = query.toLowerCase().trim();
    return products.where((p) {
      final matchesCategory = category == null || category == 'All' || p.category == category;
      if (q.isEmpty) return matchesCategory;
      final matchesQuery =
          p.name.toLowerCase().contains(q) ||
          (p.variant?.toLowerCase().contains(q) ?? false) ||
          (p.sku?.contains(q) ?? false);
      return matchesCategory && matchesQuery;
    }).toList();
  }
}

/// Represents a single entry in the Philippine product catalog.
class PhProduct {
  final String name;
  final String category;
  final String? variant;
  final String? sku; // barcode / product code

  const PhProduct({
    required this.name,
    required this.category,
    this.variant,
    this.sku,
  });

  /// Display string shown in the list tile subtitle.
  String get displayVariant => variant ?? '';

  /// The full display name including variant for disambiguation.
  String get fullName => variant != null ? '$name ($variant)' : name;
}
